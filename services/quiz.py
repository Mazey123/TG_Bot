class QuizService:
    @staticmethod
    def question_by_id(question_id: int) -> QuizQuestion | None:
        return QUESTION_BY_ID.get(question_id)

    @staticmethod
    def questions_for(category: str, rng: random.Random | None = None) -> list[QuizQuestion]:
        pool = [question for question in QUESTIONS if question.category == category]
        if len(pool) < QUESTION_LIMIT:
            raise ValueError("Недостаточно вопросов в категории")
        chooser = rng or random.SystemRandom()
        return chooser.sample(pool, QUESTION_LIMIT)

    @staticmethod
    def score(answers: list[bool]) -> int:
        return sum(1 for answer in answers if answer)

    @staticmethod
    def xp_for(correct: int, total: int) -> int:
        if total <= 0:
            return 0
        return correct * XP_PER_CORRECT + (PERFECT_BONUS if correct == total else 0)


QUESTION_BY_ID: dict[int, QuizQuestion] = {question.id: question for question in QUESTIONS}
